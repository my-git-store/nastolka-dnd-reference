export function restoreMissingReaction(id, body) {
  const reaction = reactions.get(id);
  if (!reaction) return body;
  const [name, trigger, response] = reaction;
  const section = `#### Реакции\n\n**_${name}._** *Триггер:* ${trigger} *Ответ:* ${response}`;
  if (body.includes(section)) return body;
  if (/^#### Реакции$/m.test(body)) throw new Error("Проверьте изменившийся раздел реакций: " + id);
  const legendary = body.indexOf("#### Легендарные действия");
  if (legendary === -1) return body.trimEnd() + "\n\n" + section;
  return body.slice(0, legendary) + section + "\n\n" + body.slice(legendary);
}
